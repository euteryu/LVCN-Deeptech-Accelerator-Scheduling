type DeepFusionScheduleKind = "programme" | "business_meeting" | "third_party";

const deepFusionSchedule = (
  id: string,
  date: string,
  title: string,
  startsAt: string,
  endsAt: string,
  kind: DeepFusionScheduleKind,
  location: string,
  note = "",
  decision: "Pending" | "Confirmed" = "Pending",
): ScheduleItem => {
  const itemType =
    kind === "programme"
      ? "lvnc_core"
      : kind === "business_meeting"
        ? "business_meeting"
        : "third_party";
  return {
    id,
    title,
    description: note || "DeepFusion AI schedule item from the SVC workbook.",
    itemType,
    visibilityScope: "selected_organisations",
    organisationIds: [organisations[0].id],
    attendanceRule: kind === "programme" ? "compulsory" : "optional",
    startsAt: workbookAt(date, startsAt),
    endsAt: workbookAt(date, endsAt),
    timePrecision: "exact",
    location,
    costType: note.includes("£") ? "paid" : "unknown",
    costNote: note || undefined,
    status: kind === "programme" ? "confirmed" : "proposed",
    bookingStatus:
      kind === "programme"
        ? "not_required"
        : kind === "business_meeting"
          ? "details_to_verify"
          : "to_register",
    priority: "conditional",
    nextAction:
      decision === "Confirmed"
        ? "Confirmed by DeepFusion AI."
        : "Review details and confirm.",
    sourceNote: "Imported from SVC London - DeepFusion AI Schedule.xlsx",
    responses: [
      {
        organisationId: organisations[0].id,
        decision: decision === "Confirmed" ? "going" : "undecided",
        updatedAt: new Date().toISOString(),
      },
    ],
  };
};

