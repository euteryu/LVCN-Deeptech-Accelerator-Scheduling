const deepFusionMeeting = (
  id: string,
  institution: string,
  category: string,
  meetingStatus = "",
  contactName = "",
  scheduledAt = "",
  meetingNote = "",
): ScheduleItem => {
  const startsAt = scheduledAt
    ? new Date(`${scheduledAt.replace(" ", "T")}+01:00`).toISOString()
    : undefined;
  return {
    id,
    title: institution,
    description:
      meetingNote || `Potential ${category} meeting for DeepFusion AI.`,
    itemType: "business_meeting",
    visibilityScope: "selected_organisations",
    organisationIds: [organisations[0].id],
    attendanceRule: "optional",
    startsAt,
    endsAt: startsAt
      ? addHours(new Date(startsAt), 1).toISOString()
      : undefined,
    timePrecision: startsAt ? "exact" : "unknown",
    location: "London / TBC",
    costType: "not_applicable",
    status: meetingStatus === "Agreed" ? "confirmed" : "proposed",
    bookingStatus:
      meetingStatus === "Agreed"
        ? "verified"
        : meetingStatus === "Contacted"
          ? "details_to_verify"
          : "to_arrange",
    priority: "conditional",
    sourceNote:
      "Imported from SVC London - DeepFusion AI Schedule.xlsx, Meetings tab",
    meetingCategory: category,
    meetingStatus: meetingStatus || "Open",
    contactName: contactName || undefined,
    meetingNote: meetingNote || undefined,
    responses: [],
  };
};

