const monday = startOfWeek(new Date(), { weekStartsOn: 1 });
const at = (day: number, hour: number, minutes = 0) => {
  const date = setHours(addDays(monday, day), hour);
  date.setMinutes(minutes, 0, 0);
  return date;
};
const iso = (day: number, hour: number, minutes = 0) =>
  at(day, hour, minutes).toISOString();
